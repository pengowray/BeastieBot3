// Writes LanguageNameTable.Data.cs: the English name of every ISO 639 language code, keyed the way
// the site database stores a common name's language (LanguageNameTable).
//
//   node BeastieBot3.Shared/SiteData/generate-language-names.mjs [iso-codes json folder]
//
// Sources: the ISO 639-2, 639-3 and 639-5 tables of the Debian/Ubuntu iso-codes package (default
// folder /usr/share/iso-codes/json), and the English language names of CLDR, through Node's
// Intl.DisplayNames (Node is built with full ICU).
//
// Key: the ISO 639-1 code when the language has one, else its ISO 639-3 code; also the ISO 639-5
// codes of language groups and the ISO 639-2 group codes that are in neither table. "sh" and "bh"
// (withdrawn from ISO 639-1) are not keys: Serbo-Croatian is "hbs", Bihari languages "bih".
// Name: an entry of Overrides, else CLDR's English name when CLDR keeps the code as it is (CLDR
// reads "sh" as Serbian in Latin script and "tl" as Filipino, so those get the ISO name), else the
// ISO reference name without " (macrolanguage)". When two codes get the same name, the one named by
// CLDR takes its ISO name instead ("tw": CLDR "Akan", the name of "ak"; ISO "Twi").

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const isoDir = process.argv[2] ?? '/usr/share/iso-codes/json';
const here = path.dirname(fileURLToPath(import.meta.url));
const read = (file, key) => JSON.parse(fs.readFileSync(path.join(isoDir, file), 'utf8'))[key];
const iso3 = read('iso_639-3.json', '639-3');
const iso2 = read('iso_639-2.json', '639-2');
const iso5 = read('iso_639-5.json', '639-5');

// Names the site used before this table, kept as they were, and names of groups shorter than ISO's.
// "ory" is the individual language inside the macrolanguage "or", and ISO calls it Odia, CLDR's
// name for "or".
const Overrides = {
    nb: 'Norwegian Bokmål',
    cpf: 'French-based creoles',
    ory: 'Odia (individual language)',
};

const isoNames = new Map();
const Withdrawn = new Set(['sh', 'bh']);
const keyOf = (entry) => (entry.alpha_2 && !Withdrawn.has(entry.alpha_2) ? entry.alpha_2 : entry.alpha_3);
for (const entry of iso3) {
    isoNames.set(keyOf(entry), entry.name.replace(/ \(macrolanguage\)$/, ''));
}
for (const entry of iso5) {
    if (!isoNames.has(entry.alpha_3)) isoNames.set(entry.alpha_3, entry.name);
}
for (const entry of iso2) {
    const key = keyOf(entry);
    if (!isoNames.has(key) && /^[a-z]{2,3}$/.test(key)) isoNames.set(key, entry.name);
}

const cldr = new Intl.DisplayNames(['en'], { type: 'language', fallback: 'none' });
function cldrName(code) {
    try {
        if (Intl.getCanonicalLocales(code)[0].toLowerCase() !== code) return null;
        return cldr.of(code) ?? null;
    } catch {
        return null;
    }
}

const chosen = new Map();
for (const [code, iso] of isoNames) {
    const fromCldr = Overrides[code] ? null : cldrName(code);
    chosen.set(code, { name: Overrides[code] ?? fromCldr ?? iso, iso, fromCldr: fromCldr !== null });
}
// Two codes with one name: the CLDR-named one takes its ISO name.
for (let pass = 0; pass < 3; pass++) {
    const byName = new Map();
    for (const [code, entry] of chosen) {
        byName.set(entry.name, [...(byName.get(entry.name) ?? []), code]);
    }
    for (const codes of byName.values()) {
        if (codes.length < 2) continue;
        for (const code of codes) {
            const entry = chosen.get(code);
            if (entry.fromCldr && entry.iso !== entry.name) {
                console.log(`${code}: "${entry.name}" is also the name of ${codes.filter((c) => c !== code).join(', ')}; using ISO's "${entry.iso}"`);
                chosen.set(code, { name: entry.iso, iso: entry.iso, fromCldr: false });
            }
        }
    }
}
const finalNames = new Map();
for (const [code, entry] of chosen) {
    finalNames.set(entry.name, [...(finalNames.get(entry.name) ?? []), code]);
}
for (const [name, codes] of finalNames) {
    if (codes.length > 1) console.log(`Still shared: "${name}" by ${codes.join(', ')}`);
}

const lines = [...chosen.entries()]
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([code, entry]) => `${code}\t${entry.name}`);
const cs = `// Generated by generate-language-names.mjs; do not edit by hand. Run it again to update the names.
// ISO 639 tables: iso-codes ${isoCodesVersion()}. English names: CLDR (ICU ${process.versions.icu}, Unicode ${process.versions.unicode}).

namespace BeastieBot3.Shared.SiteData;

public static partial class LanguageNameTable {
    // One line per code: the code, a tab, the English name.
    private const string Data = """
${lines.join('\n')}
""";
}
`;
fs.writeFileSync(path.join(here, 'LanguageNameTable.Data.cs'), cs);
console.log(`${lines.length} codes, ${[...chosen.values()].filter((e) => e.fromCldr).length} named by CLDR`);

function isoCodesVersion() {
    try {
        const pc = fs.readFileSync('/usr/share/pkgconfig/iso-codes.pc', 'utf8');
        return pc.match(/^Version:\s*(.+)$/m)?.[1] ?? 'unknown version';
    } catch {
        return 'unknown version';
    }
}
